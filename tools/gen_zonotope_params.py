#!/usr/bin/env python3
"""Generate include/zonotope_params.hpp from config/zonotope_params.json.

This is the ONE place that turns the single-source JSON config into the
C/C++/HLS-side #define header. Run it directly, or just build anything
(`make python|cpp|hls-csim|...` from the repo root) -- the Makefiles depend
on include/zonotope_params.hpp and regenerate it automatically whenever
config/zonotope_params.json changes.

Do NOT hand-edit include/zonotope_params.hpp -- it is overwritten by this
script.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CONFIG_PATH = REPO_ROOT / "config" / "zonotope_params.json"
OUT_PATH = REPO_ROOT / "include" / "zonotope_params.hpp"

REQUIRED_KEYS = [
    "n_state", "n_input", "n_meas", "max_gen", "reduction_budget",
    "random_seed", "dt", "proc_noise_radius", "meas_noise_radius",
    "init_radius",
]


def load_config() -> dict:
    with CONFIG_PATH.open() as f:
        cfg = json.load(f)
    missing = [k for k in REQUIRED_KEYS if k not in cfg]
    if missing:
        raise ValueError(f"{CONFIG_PATH} is missing required keys: {missing}")

    n_state = int(cfg["n_state"])
    n_meas = int(cfg["n_meas"])
    max_gen = int(cfg["max_gen"])
    reduction_budget = int(cfg["reduction_budget"])

    if reduction_budget <= n_state:
        raise ValueError(
            f"reduction_budget ({reduction_budget}) must be > n_state ({n_state}) "
            "so TOPK = reduction_budget - n_state stays positive."
        )
    # Peak generator count is reached at two DIFFERENT points in the
    # predict -> reduce -> (N_MEAS strip updates, +1 column each) -> reduce
    # pipeline, never simultaneously:
    #   - right after predict (before the first reduce): REDUCTION_BUDGET + N_STATE
    #     (REDUCE_INPUT_MAX_GEN in the generated header)
    #   - right after the last strip update (before the final reduce):
    #     REDUCTION_BUDGET + N_MEAS (STEP_MEAS_MAX_GEN)
    # so MAX_GEN only needs to cover the larger of the two, not their sum.
    required = reduction_budget + max(n_state, n_meas)
    if max_gen < required:
        raise ValueError(
            f"max_gen ({max_gen}) must be >= reduction_budget + max(n_state, n_meas) "
            f"({reduction_budget} + max({n_state}, {n_meas}) = {required})"
        )
    return cfg


def render(cfg: dict) -> str:
    return f"""// AUTO-GENERATED by tools/gen_zonotope_params.py -- DO NOT EDIT BY HAND.
// Source of truth: config/zonotope_params.json
#ifndef ZONOTOPE_PARAMS_HPP
#define ZONOTOPE_PARAMS_HPP

#ifndef N_STATE
#define N_STATE               {cfg['n_state']}
#endif
#ifndef N_INPUT
#define N_INPUT               {cfg['n_input']}
#endif
#ifndef N_MEAS
#define N_MEAS                {cfg['n_meas']}
#endif
#ifndef MAX_GEN
#define MAX_GEN               {cfg['max_gen']}
#endif
#ifndef REDUCTION_BUDGET
#define REDUCTION_BUDGET      {cfg['reduction_budget']}
#endif
#ifndef RANDOM_SEED
#define RANDOM_SEED           {cfg['random_seed']}
#endif
#ifndef DT
#define DT                    {cfg['dt']}
#endif
#ifndef PROC_NOISE_RADIUS
#define PROC_NOISE_RADIUS     {cfg['proc_noise_radius']}
#endif
#ifndef MEAS_NOISE_RADIUS
#define MEAS_NOISE_RADIUS     {cfg['meas_noise_radius']}
#endif
#ifndef INIT_RADIUS
#define INIT_RADIUS           {cfg['init_radius']}
#endif

// Derived (always recomputed from the values above; never override directly).
#define TOPK                  (REDUCTION_BUDGET - N_STATE)
#define STEP_MEAS_MAX_GEN     (REDUCTION_BUDGET + N_MEAS)
#define REDUCE_INPUT_MAX_GEN  (REDUCTION_BUDGET + N_STATE)

// Compile-time guards: catch a bad override (-D... on the command line)
// before it silently produces a corrupted/undersized run.
//
// Peak generator count is hit at two DIFFERENT points in the
// predict -> reduce -> (N_MEAS strip updates) -> reduce pipeline, never
// simultaneously, so MAX_GEN only needs to cover the larger of the two
// (not REDUCTION_BUDGET + N_STATE + N_MEAS).
#if MAX_GEN < REDUCE_INPUT_MAX_GEN
#error "MAX_GEN must be >= REDUCTION_BUDGET + N_STATE (post-predict, pre-reduce peak)"
#endif
#if MAX_GEN < STEP_MEAS_MAX_GEN
#error "MAX_GEN must be >= REDUCTION_BUDGET + N_MEAS (post-strip-updates, pre-reduce peak)"
#endif
#if (REDUCTION_BUDGET - N_STATE) <= 0
#error "REDUCTION_BUDGET must be > N_STATE (TOPK must stay positive)"
#endif

#endif  // ZONOTOPE_PARAMS_HPP
"""


def main() -> int:
    cfg = load_config()
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(render(cfg))
    print(f"Generated {OUT_PATH} from {CONFIG_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
